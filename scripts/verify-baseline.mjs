// CA-04: proves the installed Pixel Agents (and its launcher scripts) were not modified by this project.
// Read-only against the real targets. Node built-ins only.
//   node scripts/verify-baseline.mjs            -> compares against baseline-hashes.json ("idêntico" / differences, exit 0/1)
//   node scripts/verify-baseline.mjs --update   -> (re)writes baseline-hashes.json (explicit flag only)
//
// Strategy: one SHA-256 per file (paths sorted, relative, "/" separators) plus a deterministic aggregate
// per root (SHA-256 of "<path>\0<sha>\n" lines). Only paths and hashes are stored, never file contents.
// Secrets are never hashed: the hooks dir keeps only script extensions and skips token/characters files.
import { createHash } from 'node:crypto';
import {
  existsSync,
  readFileSync,
  readdirSync,
  renameSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const BASELINE_FILE = resolve(
  HERE,
  '..',
  'docs',
  'projeto',
  '2026-11-12-escritorio-equipe',
  'baseline-hashes.json',
);

const SCRIPT_EXT = new Set(['.js', '.cjs', '.mjs', '.sh', '.bat', '.cmd', '.ps1']);
const SECRET_NAME = /token|secret|credential|characters\.json/i;

/** Default roots on this machine. kind: tree = whole directory; scripts = hook scripts only; files = fixed list. */
export function defaultRoots(home = homedir(), appData = process.env.APPDATA) {
  const roaming = appData || join(home, 'AppData', 'Roaming');
  return [
    {
      id: 'pixel-agents-package',
      kind: 'tree',
      path: join(roaming, 'npm', 'node_modules', 'pixel-agents'),
    },
    { id: 'pixel-agents-hooks', kind: 'scripts', path: join(home, '.pixel-agents', 'hooks') },
    {
      id: 'pixel-agents-launchers',
      kind: 'files',
      path: join(home, 'pixel-agents'),
      files: ['abrir-escritorio.bat', 'iniciar-painel.bat'],
    },
  ];
}

function sha256File(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

function walk(dir, base = '') {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out;
}

function listFiles(root) {
  if (!existsSync(root.path)) return [];
  if (root.kind === 'files') return root.files.filter((f) => existsSync(join(root.path, f)));
  const all = walk(root.path);
  if (root.kind === 'scripts') {
    return all.filter((f) => {
      const dot = f.lastIndexOf('.');
      return (
        !f.includes('/') &&
        dot >= 0 &&
        SCRIPT_EXT.has(f.slice(dot).toLowerCase()) &&
        !SECRET_NAME.test(f)
      );
    });
  }
  return all;
}

function aggregate(files) {
  const h = createHash('sha256');
  for (const p of Object.keys(files).sort()) h.update(`${p}\0${files[p]}\n`);
  return h.digest('hex');
}

/** Computes { rootId: { kind, fileCount, aggregate, files: {relPath: sha256} } } for the given roots. */
export function computeSnapshot(roots) {
  const snapshot = {};
  for (const root of roots) {
    const files = {};
    for (const rel of listFiles(root).sort()) {
      try {
        files[rel] = sha256File(join(root.path, rel));
      } catch {
        files[rel] = 'unreadable';
      }
    }
    snapshot[root.id] = {
      kind: root.kind,
      fileCount: Object.keys(files).length,
      aggregate: aggregate(files),
      files,
    };
  }
  return snapshot;
}

/** Returns a sorted list of human-readable differences (empty = identical). */
export function compareSnapshots(expected, actual) {
  const diffs = [];
  for (const id of Object.keys(expected).sort()) {
    const exp = expected[id].files;
    const act = actual[id]?.files ?? {};
    for (const p of Object.keys(exp).sort()) {
      if (!(p in act)) diffs.push(`REMOVIDO  [${id}] ${p}`);
      else if (act[p] !== exp[p]) diffs.push(`ALTERADO  [${id}] ${p}`);
    }
    for (const p of Object.keys(act).sort()) {
      if (!(p in exp)) diffs.push(`ADICIONADO [${id}] ${p}`);
    }
  }
  for (const id of Object.keys(actual)) {
    if (!(id in expected)) diffs.push(`RAIZ NOVA [${id}]`);
  }
  return diffs;
}

export function buildBaseline(roots, now = new Date()) {
  return {
    version: 1,
    note: 'SHA-256 per file; only paths and hashes, never contents. Secrets (tokens, characters.json) are excluded. Generated by scripts/verify-baseline.mjs --update.',
    createdAt: now.toISOString(),
    roots: computeSnapshot(roots),
  };
}

export function verify(baseline, roots) {
  const diffs = compareSnapshots(baseline.roots, computeSnapshot(roots));
  return { identical: diffs.length === 0, diffs };
}

function main(argv) {
  const roots = defaultRoots();
  if (argv.includes('--update')) {
    const missing = roots.filter((r) => !existsSync(r.path));
    if (missing.length) {
      console.error(`Raiz ausente, nada gravado: ${missing.map((r) => r.id).join(', ')}`);
      return 1;
    }
    const baseline = buildBaseline(roots);
    const tmp = `${BASELINE_FILE}.tmp`;
    writeFileSync(tmp, `${JSON.stringify(baseline, null, 2)}\n`, 'utf8');
    renameSync(tmp, BASELINE_FILE); // atomic replace
    for (const [id, s] of Object.entries(baseline.roots)) {
      console.log(`${id}: ${s.fileCount} arquivos, agregado ${s.aggregate}`);
    }
    console.log(`Baseline gravada em ${BASELINE_FILE}`);
    return 0;
  }
  if (!existsSync(BASELINE_FILE) || !statSync(BASELINE_FILE).isFile()) {
    console.error(`Baseline não encontrada: ${BASELINE_FILE} (use --update)`);
    return 1;
  }
  const result = verify(JSON.parse(readFileSync(BASELINE_FILE, 'utf8')), roots);
  if (result.identical) {
    console.log('idêntico');
    return 0;
  }
  console.log(`DIFERENÇAS (${result.diffs.length}):`);
  for (const d of result.diffs.slice(0, 200)) console.log(`  ${d}`);
  if (result.diffs.length > 200) console.log(`  ... +${result.diffs.length - 200}`);
  return 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
